#!/usr/bin/env python3
"""Write (or check) the DriftResampler's polyphase interpolation table.

    tools/design_drift_table.py --write    regenerate src/shared/audiodsp_drift_table.h
    tools/design_drift_table.py --verify   check the shipped table is this script's

`audiopump.DriftResampler` reads its input between samples with a 32-tap
Kaiser-windowed sinc. The kernel is tabulated at 128 fractional positions
(plus the 129th, the first one moved one whole sample, so row p + 1 always
exists) and the resampler interpolates linearly between two neighbouring
rows. Each row is scaled to sum to exactly 1, so a constant input comes out
unchanged at every fractional position.

The table is a checked-in constant rather than something each runtime
computes, because CircuitPython's floats are single precision and its libm
is not glibc's: a table built at run time would be a different table on
each target, and every target has to render the node identically.

Pure Python, no numpy: the numbers here are the ones the C ships.
"""

import argparse
import math
import pathlib
import struct
import sys

TAPS = 32
PHASES = 128
#: The cutoff as a fraction of the input sample rate. 0.45 keeps the passband
#: flat to 20 kHz at 48 kHz within about 1 dB and stops above 0.55.
CUTOFF = 0.45
#: Kaiser's beta. 9 puts the stopband near -90 dB, below 16-bit audio's floor.
BETA = 9.0

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "src" / "shared" / "audiodsp_drift_table.h"


def bessel_i0(x):
    """The modified Bessel function of order 0, by its power series."""
    total = term = 1.0
    k = 1
    while term > 1e-17 * total:
        term *= (x / (2.0 * k)) ** 2
        total += term
        k += 1
    return total


def kaiser(t):
    x = t / (TAPS / 2)
    if abs(x) > 1.0:
        return 0.0
    return bessel_i0(BETA * math.sqrt(1.0 - x * x)) / bessel_i0(BETA)


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def table():
    """Rows 0..PHASES, each TAPS float32s summing to 1.

    Tap k of row p sits `k - (TAPS/2 - 1) - p/PHASES` input samples from the
    point being read, so row 0 reads exactly on a sample and row PHASES reads
    exactly on the next one."""
    rows = []
    for p in range(PHASES + 1):
        row = []
        for k in range(TAPS):
            t = k - (TAPS // 2 - 1) - p / PHASES
            row.append(2 * CUTOFF * sinc(2 * CUTOFF * t) * kaiser(t))
        total = sum(row)
        rows.append([f32(v / total) for v in row])
    return rows


def render(rows):
    lines = [
        "// Generated by tools/design_drift_table.py. Do not edit by hand:",
        "// change the script and run it with --write.",
        "//",
        f"// {TAPS}-tap Kaiser-windowed sinc (beta {BETA:g}, cutoff {CUTOFF:g} of",
        f"// the input rate) at {PHASES} + 1 fractional positions, each row",
        "// scaled to sum to 1.",
        "//",
        "// SPDX-License-Identifier: MIT",
        "",
        "#pragma once",
        "",
        "#include \"shared/audiodsp_drift.h\"",
        "",
        "static const float audiodsp_drift_table"
        "[AUDIODSP_DRIFT_PHASES + 1][AUDIODSP_DRIFT_TAPS] = {",
    ]
    for row in rows:
        lines.append("    {")
        for i in range(0, TAPS, 4):
            cells = ", ".join(f"{v!r}f" if v != 0 else "0.0f"
                              for v in (float(f"{x:.9g}") for x in row[i:i + 4]))
            lines.append(f"        {cells},")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    text = render(table())
    if args.write:
        HEADER.write_text(text)
        print(f"wrote {HEADER.relative_to(ROOT)}")
        return 0
    if HEADER.read_text() != text:
        print(f"{HEADER.relative_to(ROOT)} is not what this script writes")
        return 1
    print("table matches")
    return 0


if __name__ == "__main__":
    sys.exit(main())
